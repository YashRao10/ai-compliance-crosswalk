def render_html(subject: str, findings_data: dict, controls: dict) -> str:
    findings = findings_data["findings"]
    summary = compute_summary(findings)
    cards = "\n".join(render_finding_row(f, controls) for f in findings)
    remediation_items = "\n".join(f"<li>{html.escape(p)}</li>" for p in remediation_paths(findings, controls))
    return PAGE_TEMPLATE.format(
        subject=html.escape(subject),
        assessed_at=html.escape(findings_data.get("assessed_at_utc", "unknown")),
        assessed_by=html.escape(findings_data.get("assessed_by", "unknown")),
        met=summary["Met"],
        partial=summary["Partial"],
        gap=summary["Gap"],
        total=summary["total"],
        cards=cards,
        verdict=html.escape(verdict_text(summary)),
        remediation_items=remediation_items,
    )


def write_report(subject: str) -> tuple[Path, Path]:
    findings_data = load_findings(subject)
    controls = controls_by_id()

    unknown = [f["control_id"] for f in findings_data["findings"] if f["control_id"] not in controls]
    if unknown:
        raise ValueError(f"findings reference unknown control id(s): {unknown}")

    summary = compute_summary(findings_data["findings"])
    ts = datetime.now(timezone.utc).strftime("%Y%m%d-%H%M%S")

    REPORTS_DIR.mkdir(exist_ok=True)
    json_path = REPORTS_DIR / f"{subject}-{ts}.json"
    html_path = REPORTS_DIR / f"{subject}-{ts}.html"

    json_path.write_text(
        json.dumps({"subject": subject, "summary": summary, **findings_data}, indent=2),
        encoding="utf-8",
    )
    html_path.write_text(render_html(subject, findings_data, controls), encoding="utf-8")
    return json_path, html_path


def run():
    parser = argparse.ArgumentParser()
    parser.add_argument("subject", help="e.g. portfolio-sync, do178c-build-test")
    args = parser.parse_args()
    json_path, html_path = write_report(args.subject)
    print(f"Wrote {json_path}")
    print(f"Wrote {html_path}")


if __name__ == "__main__":
    run()
