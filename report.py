import json
from datetime import datetime, timezone
from pathlib import Path

from controls import controls_by_id

REPO_ROOT = Path(__file__).resolve().parent
FINDINGS_DIR = REPO_ROOT / "findings"
REPORTS_DIR = REPO_ROOT / "reports"

COVERAGE_META = {
    "Met": {"color": "#22c55e", "bg": "rgba(34,197,94,0.12)"},
    "Partial": {"color": "#f59e0b", "bg": "rgba(245,158,11,0.14)"},
    "Gap": {"color": "#ef4444", "bg": "rgba(239,68,68,0.14)"},
}


def load_findings(subject: str) -> dict:
    path = FINDINGS_DIR / f"{subject}-findings.json"
    if not path.exists():
        raise FileNotFoundError(
            f"No findings file for '{subject}' at {path}. Findings are written "
            "in-session (see README.md), not generated by this script."
        )
    return json.loads(path.read_text(encoding="utf-8"))


def compute_summary(findings: list[dict]) -> dict:
    counts = {"Met": 0, "Partial": 0, "Gap": 0}
    flagged = 0
    for f in findings:
        counts[f["coverage"]] += 1
        if f.get("needs_human_review"):
            flagged += 1
    return {**counts, "total": len(findings), "needs_human_review": flagged}


def verdict_text(summary: dict) -> str:
    if summary["Gap"] == 0 and summary["needs_human_review"] == 0:
        return (
            "No outright gaps found, and every verdict was reached with high "
            "enough confidence to stand without a human re-check. Partial "
            "coverage still means real work remains before this would satisfy "
            "a formal conformity assessment."
        )
    parts = []
    if summary["Gap"]:
        parts.append(f"{summary['Gap']} control(s) have no real coverage yet")
    if summary["needs_human_review"]:
        parts.append(
            f"{summary['needs_human_review']} finding(s) are flagged for human "
            "review rather than treated as settled"
        )
    return "; ".join(parts) + "."


def remediation_paths(findings: list[dict], controls: dict) -> list[str]:
    paths = []
    for f in findings:
        if f["coverage"] == "Gap":
            title = controls[f["control_id"]]["title"]
            paths.append(f"Close the gap on {title} ({f['control_id']}) — currently no real coverage.")
        elif f.get("needs_human_review"):
            title = controls[f["control_id"]]["title"]
            reason = f.get("human_review_reason", "flagged low-confidence verdict")
            paths.append(f"Resolve open question on {title} ({f['control_id']}): {reason}")
    if not paths:
        paths.append("No outstanding gaps or flagged findings — next step is periodic re-assessment, not remediation.")
    return paths


def render_finding_row(f: dict, controls: dict) -> str:
    control = controls[f["control_id"]]
    meta = COVERAGE_META[f["coverage"]]
    flag_html = ""
    if f.get("needs_human_review"):
        flag_html = (
            f'<div class="flag">NEEDS HUMAN REVIEW — {html.escape(f.get("human_review_reason", ""))}</div>'
        )
    return f"""
    <details class="card">
      <summary>
        <span class="badge" style="color:{meta['color']};background:{meta['bg']}">{f['coverage']}</span>
        <span class="control-id">{html.escape(f['control_id'])}</span>
        <span class="control-title">{html.escape(control['title'])}</span>
        <span class="framework-pill">{html.escape(control['framework'])}</span>
      </summary>
      <div class="card-body">
        <div class="field"><span class="field-label">What would satisfy this</span>{html.escape(control['what_would_satisfy_this'].strip())}</div>
        <div class="field"><span class="field-label">Rationale</span>{html.escape(f['rationale'])}</div>
        <div class="field"><span class="field-label">Confidence</span>{html.escape(f['confidence'])}</div>
        {flag_html}
      </div>
    </details>
    """


