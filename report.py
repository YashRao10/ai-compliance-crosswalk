"""Pure formatter: reads a findings.json file (produced in-session, not by
this script — see README.md) and renders it as a JSON summary + a
self-contained HTML dashboard. Makes no assessment judgments and no API
calls; the crosswalk table / gap matrix / verdict / remediation-paths shape
follows AAS-DO178-Demo's DO-330 case study, and the HTML theme reuses
ai-security/harness/generate_html_report.py's dark "security terminal" style
for visual consistency with its sibling project.

Usage:
    python report.py <subject>          # e.g. python report.py portfolio-sync
"""

import argparse
